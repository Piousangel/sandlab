// 리디자인 P11a 홈 랙 e2e: 재료·도크 툴바 로빙, 선택 관 한 번 붓기(재생·제거·탭 전환·틈·reduced-motion·미리 받기 0).
//   pnpm build:preview && <out/ 정적 서버> && NODE_PATH=<playwright 있는 곳> node scripts/qa/home-rack-e2e.cjs http://localhost:4300 [capDir]
// 헤드리스에는 WebGPU 어댑터가 없어 홈이 미지원 화면으로 간다 → requestAdapter를 끝나지 않는 약속으로 바꿔 랙이 있는 화면에 머문다(엔진 시작 전 상태).
const { chromium } = require('playwright')
const BASE = process.argv[2] || 'http://localhost:4300'
const S = process.argv[3] || require('os').tmpdir()
const ok = [], bad = []
const t = (c, m) => (c ? ok : bad).push(m)
const INIT = () => {
  try { localStorage.setItem('sl.pourdemo.v1', '1') } catch {}
  if (navigator.gpu) navigator.gpu.requestAdapter = () => new Promise(() => {})
}
;(async () => {
  const b = await chromium.launch()
  async function page(opts = {}) {
    const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, reducedMotion: opts.reduce ? 'reduce' : 'no-preference' })
    const p = await ctx.newPage()
    p.on('pageerror', (e) => bad.push('pageerror ' + e.message))
    await p.addInitScript(INIT)
    await p.goto(BASE + '/')
    await p.waitForSelector('.sl-tube-btn')
    await p.waitForTimeout(500)
    return p
  }
  const act = (p) => p.evaluate(() => ({ n: document.activeElement.textContent.trim(), pr: document.activeElement.getAttribute('aria-pressed'), al: document.activeElement.getAttribute('aria-label') }))
  let p = await page()
  const stops = await p.$$eval('[aria-label="Material"] .sl-tube-btn', (bs) => bs.filter((b) => b.tabIndex === 0).map((b) => b.textContent))
  t(stops.length === 1 && stops[0] === 'sand', 'tab stop 1 = sand ' + stops)
  await p.focus('#sl-rack-tab-all')
  await p.keyboard.press('Tab')
  let f = await act(p)
  t(f.n === 'sand', 'Tab from tablist lands on sand: ' + f.n)
  await p.keyboard.press('ArrowRight')
  f = await act(p)
  t(f.n !== 'sand' && f.pr === 'false', 'ArrowRight moves focus only: ' + JSON.stringify(f))
  await p.waitForTimeout(400)
  await p.keyboard.press('Enter')
  await p.waitForTimeout(60)
  let ov = await p.$$eval('[data-sl-pour]', (e) => e.map((x) => x.dataset.slPour))
  t(ov.length === 1 && ov[0] === f.n, 'Enter selects + pour overlay ' + ov)
  await p.waitForTimeout(900)
  t((await p.$$('[data-sl-pour]')).length === 0, 'overlay removed after animation')
  t((await act(p)).pr === 'true', 'selected now pressed')
  await p.keyboard.press('End')
  const fe = (await act(p)).n
  await p.waitForTimeout(700)
  const vis = await p.evaluate(() => { const r = document.activeElement.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth })
  t(vis, 'End -> ' + fe + ' scrolled into view')
  await p.keyboard.press('Home')
  t((await act(p)).n === 'sand', 'Home -> sand')
  // Tab out and back returns to last focused
  await p.keyboard.press('Tab')
  await p.keyboard.press('Shift+Tab')
  t((await act(p)).n === 'sand', 'Tab out/in returns to last focused (sand)')
  const sel = await p.$('[aria-label="Material"] [aria-pressed="true"]')
  await sel.click()
  await p.waitForTimeout(50)
  t((await p.$$('[data-sl-pour]')).length === 0, 're-click selected: no pour')
  await p.click('#sl-rack-tab-solid')
  await p.waitForTimeout(100)
  await (await p.$('[aria-label="Material"] .sl-tube-btn')).click()
  await p.waitForTimeout(50)
  t((await p.$$('[data-sl-pour]')).length === 0, 'solid: no pour')
  t((await p.$$eval('[aria-label="Material"] .sl-tube-btn', (bs) => bs.filter((b) => b.tabIndex === 0).length)) === 1, 'solid tab: 1 stop')
  await p.click('#sl-rack-tab-liquid')
  await p.waitForTimeout(100)
  await (await p.$('[aria-label="Material"] .sl-tube-btn')).click()
  await p.waitForTimeout(80)
  const geo = await p.evaluate(() => { const o = document.querySelector('[data-sl-pour]'); if (!o) return null; const g = o.parentElement; const a = o.getBoundingClientRect(), c = g.getBoundingClientRect(); return { ox: Math.round(a.left - c.left), oy: Math.round(a.top - c.top), oh: a.height, ch: c.height } })
  t(geo && Math.abs(geo.oh - (geo.ch - 3)) < 0.5, 'mouse click pour overlay geometry ' + JSON.stringify(geo))
  await p.waitForTimeout(200)
  const rack = await p.$('.sl-rack')
  await rack.screenshot({ path: S + '/p11a-water-mid.png' })
  await p.waitForTimeout(800)
  await rack.screenshot({ path: S + '/p11a-water-end.png' })
  // 리뷰 차단 재현: 재생 중 탭을 바꿨다 돌아오면 혼자 다시 붓지 않는다 / 오버레이가 유리 안쪽을 다 덮는다(아래 1px 틈 0)
  await p.click('#sl-rack-tab-all')
  await p.waitForTimeout(50)
  const all = await p.$$('[aria-label="Material"] .sl-tube-btn')
  await all[2].hover()
  await p.waitForTimeout(300)
  await all[2].click()
  await p.waitForTimeout(80)
  const gap = await p.evaluate(() => {
    const o = document.querySelector('[data-sl-pour]')
    if (!o) return null
    const r = o.parentElement.getBoundingClientRect()
    return Math.round(r.bottom - 2 - o.getBoundingClientRect().bottom)
  })
  t(gap === 0, 'overlay bottom gap 0 (' + gap + ')')
  await p.click('#sl-rack-tab-gas')
  await p.waitForTimeout(80)
  await p.click('#sl-rack-tab-all')
  await p.waitForTimeout(50)
  t((await p.$$('[data-sl-pour]')).length === 0, 'tab switch mid-pour: no replay')
  const ds = await p.$$eval('[aria-label="Brush"] button', (bs) => bs.map((b) => b.tabIndex))
  t(ds.filter((x) => x === 0).length === 1 && ds.length === 5, 'dock 1 stop of 5 ' + ds)
  await p.focus('[aria-label="Brush"] button[tabindex="0"]')
  await p.keyboard.press('ArrowRight')
  t((await act(p)).al === 'Small brush', 'dock ArrowRight -> small brush')
  await p.keyboard.press('ArrowLeft')
  await p.keyboard.press('ArrowLeft')
  t((await act(p)).n === 'Share', 'dock wrap -> Share')
  await p.keyboard.press('Tab')
  t(await p.evaluate(() => document.activeElement.closest('[aria-label="Brush"]') === null), 'Tab leaves dock in one press')
  await p.context().close()

  p = await page({ reduce: true })
  const net = []
  p.on('request', (r) => { if (r.url().includes('/strips/')) net.push(r.url()) })
  await p.click('#sl-rack-tab-liquid')
  await (await p.$$('[aria-label="Material"] .sl-tube-btn'))[1].hover()
  await (await p.$('[aria-label="Material"] .sl-tube-btn')).click()
  await p.waitForTimeout(300)
  t((await p.$$('[data-sl-pour]')).length === 0, 'reduced-motion: no pour')
  t(net.length === 0, 'reduced-motion: no strip fetch ' + net.length)
  await p.context().close()

  const ctx = await b.newContext({ viewport: { width: 390, height: 844 } })
  const q = await ctx.newPage()
  const n = []
  q.on('request', (r) => { if (r.url().includes('/strips/')) n.push(r.url()) })
  await q.addInitScript(INIT)
  await q.goto(BASE + '/')
  await q.waitForTimeout(3000)
  t(n.length === 0, 'idle visit without stroke: no strip fetched (' + n.length + ')')
  await b.close()
  console.log(ok.map((x) => 'ok   ' + x).join('\n'))
  console.log(bad.map((x) => 'FAIL ' + x).join('\n'))
  console.log(`${ok.length}/${ok.length + bad.length}`)
  process.exit(bad.length ? 1 : 0)
})()
